# Demonstrating the use of the type() function in Python

# Integer
from typing import Type


num = 10
print(type(num))  # <class 'int'>

# Float
decimal = 3.14
print(type(decimal))  # <class 'float'>

# String
text = "Hello"
print(type(text))  # <class 'str'>

# Boolean
flag = True
print(type(flag))  # <class 'bool'>