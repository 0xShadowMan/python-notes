name = "Coder man"

print(len(name)) # The length of the string

# Check if the string ends with the given value
print(name.endswith("man"))

# Check if the string starts with the given value
print(name.startswith("shadow"))

# Convert the first character to upper case
print(name.capitalize())

# Convert all characters to upper case
print(name.upper())

# Convert all characters to lower case
print(name.lower())

# Replace a substring with another substring
print(name.replace("Man", "name"))

# Find the position of a substring
print(name.find("Man"))

# Count occurrences of a substring
print(name.count("a"))


 # Convert the first character of each word to upper case
print(name.title())

