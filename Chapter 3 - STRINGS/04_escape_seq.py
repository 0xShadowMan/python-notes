# That \n is an escape sequence which is used to print in new line
escape = "I am a Programmer\nI practice Python programming"

print(escape)


# That \t is an escape sequence which is used to print a tab space
t = "That is a \ttab space"

print(t)

# That \""\ is an escape sequence which is used to print double quote
double_quote = "He said, \"Yor are a programmer\""

print(double_quote)



